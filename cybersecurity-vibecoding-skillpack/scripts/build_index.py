#!/usr/bin/env python3
# Generate or check skills/INDEX.md, the one-line-per-skill routing index (standard library only).
from __future__ import annotations
import argparse, re, sys
from pathlib import Path
CATS = [('core', 'Core engineering'), ('cybersecurity', 'Cybersecurity'), ('engineering', 'Supporting engineering')]

def read_meta(path: Path):
    txt = path.read_text(encoding='utf-8')
    name = re.search(r'(?m)^name:\s*(\S+)', txt).group(1)
    desc = re.search(r'(?m)^description:\s*(.+)$', txt).group(1).strip()
    return name, desc

def build(root: Path) -> str:
    lines = ['# Skill Index', '',
             'Pick skills from this table instead of opening skill files. Open one primary skill and normally at most three supports; see `SKILL_ROUTER.md` for routing rules and `instructions/COMMON_SKILL_RULES.md` for the shared rules every skill relies on.', '',
             'Generated by `python scripts/build_index.py`; `python scripts/build_index.py --check` fails if it is out of date.', '']
    for cat, label in CATS:
        paths = sorted((root / 'skills' / cat).glob('*/SKILL.md'))
        lines += [f'## {label} ({len(paths)})', '', '| Skill | Use it to |', '|---|---|']
        for p in paths:
            name, desc = read_meta(p)
            lines.append(f'| [{cat}/{name}]({cat}/{p.parent.name}/SKILL.md) | {desc} |')
        lines.append('')
    return '\n'.join(lines).rstrip('\n') + '\n'

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--root', type=Path, default=Path(__file__).resolve().parent.parent)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args(argv); root = a.root.resolve(); target = root / 'skills' / 'INDEX.md'; new = build(root)
    if a.check:
        if not target.is_file() or target.read_text(encoding='utf-8') != new:
            print('FAIL: skills/INDEX.md is missing or out of date; run python scripts/build_index.py', file=sys.stderr); return 1
        print('PASS: skills/INDEX.md is up to date'); return 0
    target.write_text(new, encoding='utf-8'); print(f'PASS: wrote {target}'); return 0
if __name__ == '__main__': raise SystemExit(main())
